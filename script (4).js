/**
 * سكريبت عرض الساعة
 * يعرض الوقت الحالي مع معالجة الأخطاء ودعم اللغات المختلفة
 */

// إعدادات الساعة
const إعدادات_الساعة = {
  معرّف_العنصر: 'currentTime',
  فترة_التحديث: 1000, // بالميلي ثانية
  اللغة: 'ar-SA', // اللغة العربية - المملكة العربية السعودية
  استخدام_التوقيت_العالمي: false
};

let معرّف_الفترة_الزمنية = null;

/**
 * عرض الوقت الحالي
 * @param {string} الصيغة - 'محلي' أو 'عالمي'
 */
function عرض_الوقت(الصيغة = 'محلي') {
  const عنصر = document.getElementById(إعدادات_الساعة.معرّف_العنصر);
  
  if (!عنصر) {
    console.error(`العنصر #${إعدادات_الساعة.معرّف_العنصر} غير موجود`);
    return;
  }
  
  const التاريخ = new Date();
  const الوقت_المنسّق = الصيغة === 'عالمي' 
    ? التاريخ.toUTCString() 
    : التاريخ.toLocaleString(إعدادات_الساعة.اللغة);
  
  عنصر.innerHTML = الوقت_المنسّق;
}

/**
 * سكريبت عرض الساعة
 * يعرض الوقت الحالي مع معالجة الأخطاء ودعم اللغات المختلفة
 */

// إعدادات الساعة
const إعدادات_الساعة = {
  معرّف_العنصر: 'currentTime',
  فترة_التحديث: 1000, // بالميلي ثانية
  اللغة: 'ar-SA', // اللغة العربية - المملكة العربية السعودية
  استخدام_التوقيت_العالمي: false
};

let معرّف_الفترة_الزمنية = null;

/**
 * عرض الوقت الحالي
 * @param {string} الصيغة - 'محلي' أو 'عالمي'
 */
function عرض_الوقت(الصيغة = 'محلي') {
  const عنصر = document.getElementById(إعدادات_الساعة.معرّف_العنصر);
  
  if (!عنصر) {
    console.error(`العنصر #${إعدادات_الساعة.معرّف_العنصر} غير موجود`);
    return;
  }
  
  const التاريخ = new Date();
  const الوقت_المنسّق = الصيغة === 'عالمي' 
    ? التاريخ.toUTCString() 
    : التاريخ.toLocaleString(إعدادات_الساعة.اللغة);
  
  عنصر.innerHTML = الوقت_المنسّق;
}

/**
 * بدء تشغيل الساعة
 */
function بدء_الساعة() {
  عرض_الوقت();
  معرّف_الفترة_الزمنية = setInterval(() => {
    عرض_الوقت(إعدادات_الساعة.استخدام_التوقيت_العالمي ? 'عالمي' : 'محلي');
  }, إعدادات_الساعة.فترة_التحديث);
  console.log('✅ تم بدء تشغيل الساعة');
}

/**
 * إيقاف الساعة
 */
function إيقاف_الساعة() {
  if (معرّف_الفترة_الزمنية) {
    clearInterval(معرّف_الفترة_الزمنية);
    معرّف_الفترة_الزمنية = null;
    console.log('⏹️ تم إيقاف الساعة');
  }
}

/**
 * تغيير صيغة الوقت
 * @param {boolean} استخدام_التوقيت - true للتوقيت العالمي، false للتوقيت المحلي
 */
function تغيير_صيغة_الوقت(استخدام_التوقيت) {
  إعدادات_الساعة.استخدام_التوقيت_العالمي = استخدام_التوقيت;
  عرض_الوقت(استخدام_التوقيت ? 'عالمي' : 'محلي');
  console.log(`🔄 تم تغيير الصيغة إلى: ${استخدام_التوقيت ? 'التوقيت العالمي' : 'التوقيت المحلي'}`);
}

/**
 * تغيير اللغة
 * @param {string} كود_اللغة - كود اللغة (مثل: ar-SA, en-US)
 */
function تغيير_اللغة(كود_اللغة) {
  إعدادات_الساعة.اللغة = كود_اللغة;
  عرض_الوقت();
  console.log(`🌐 تم تغيير اللغة إلى: ${كود_اللغة}`);
}

// تهيئة الساعة عند تحميل الصفحة
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', بدء_الساعة);
} else {
  بدء_الساعة();
}

// تصدير الدوال للاستخدام الخارجي
window.عرض_الوقت = عرض_الوقت;
window.بدء_الساعة = بدء_الساعة;
window.إيقاف_الساعة = إيقاف_الساعة;
window.تغيير_صيغة_الوقت = تغيير_صيغة_الوقت;
window.تغيير_اللغة = تغيير_اللغة;
